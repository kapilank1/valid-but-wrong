// Downsamples a real Falcon 9 ascent (data/processed/falcon9/<slug>.csv) to 1 Hz and writes it as a
// TypeScript module, so mock mode replays real webcast telemetry without needing the backend.
// Usage: node scripts/gen-mock-profile.mjs [slug]   (default: ses-9)
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, "../../..");
const slug = process.argv[2] ?? "ses-9";

const index = JSON.parse(readFileSync(resolve(repo, "data/processed/falcon9/index.json"), "utf8"));
const meta = index.find((m) => m.slug === slug);
if (!meta) throw new Error(`unknown slug ${slug}`);

const lines = readFileSync(resolve(repo, `data/processed/falcon9/${slug}.csv`), "utf8").trim().split("\n");
const header = lines[0].split(",");
const channels = header.slice(1);
const step = Math.round(meta.rate_hz); // keep one row per second
const rows = [];
for (let i = 1; i < lines.length; i += step) {
  const cols = lines[i].split(",").map(Number);
  rows.push(cols.slice(1).map((v) => Number(v.toFixed(2))));
}

const out = `// GENERATED by scripts/gen-mock-profile.mjs from data/processed/falcon9/${slug}.csv. Do not edit.
// Real Falcon 9 webcast telemetry (shahar603/Telemetry-Data), downsampled to 1 Hz.
export const FALCON9_PROFILE = {
  slug: ${JSON.stringify(slug)},
  missionName: ${JSON.stringify(meta.mission_name)},
  dt: 1,
  channels: ${JSON.stringify(channels)} as const,
  events: ${JSON.stringify(meta.events)} as Record<string, number>,
  rows: ${JSON.stringify(rows)} as number[][],
};
`;
writeFileSync(resolve(here, "../src/lib/mock/falcon9Profile.ts"), out);
console.log(`wrote ${rows.length} rows for ${slug}`);
